"""Class model for IV.3 (8 feature groups). Single source for draw.io and Mermaid.

Rows are read top to bottom: controller, services (and classes owned by another group,
shown by name only as `ref`), externals or helpers, then entities and enumerations.
Operations follow the sequence messages in diagrams/08-sequence (2026-11-03 alignment).
"""


def C(name, stereo, row, attrs=(), ops=(), literals=()):
    return dict(name=name, stereo=stereo, row=row, attrs=list(attrs), ops=list(ops), literals=list(literals))


def ref(name, row=1, stereo='service'):
    """Class owned by another group; drawn with its name only."""
    return dict(name=name, stereo=stereo, row=row, attrs=[], ops=[], literals=[], ref=True)


def R(source, target, label='', kind='dependency', mult=None):
    return dict(source=source, target=target, label=label, kind=kind, mult=mult)


